"""Domain data models for targets, observations, verdicts, findings, and reports."""

from __future__ import annotations

import time
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class VerdictKind(str, Enum):
    """Categorical classification outcome for a probe or policy check."""

    OPEN = "OPEN"
    DROPPED = "DROPPED"
    RESET = "RESET"
    REJECTED = "REJECTED"
    INTERCEPTED = "INTERCEPTED"
    TAMPERED = "TAMPERED"
    OK = "OK"
    UNKNOWN = "UNKNOWN"
    BLOCKED_DROP = "BLOCKED_DROP"
    BLOCKED_RESET = "BLOCKED_RESET"
    BLOCKED_ICMP = "BLOCKED_ICMP"
    CLOSED_OR_RESET = "CLOSED_OR_RESET"
    LOSSY = "LOSSY"
    CLEAN = "CLEAN"
    REWRITTEN = "REWRITTEN"
    MISMATCH = "MISMATCH"
    HEADERS_INJECTED = "HEADERS_INJECTED"
    BODY_MODIFIED = "BODY_MODIFIED"
    PROXIED = "PROXIED"
    REDIRECTED = "REDIRECTED"


# Backwards compatibility alias
VerdictStatus = VerdictKind


class Confidence(str, Enum):
    """Statistical confidence level of a classifier verdict."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


# Backwards compatibility alias
ConfidenceLevel = Confidence


class Severity(str, Enum):
    """Risk/impact severity of a policy finding."""

    CRITICAL = "critical"
    HIGH = "high"
    WARN = "warn"
    MEDIUM = "medium"
    LOW = "low"
    INFO = "info"


class Target(BaseModel):
    """Network target specification."""

    model_config = {"frozen": True}

    host: str
    ip: str | None = None
    port: int | None = None
    protocol: str = "tcp"
    service: str | None = None
    expect_open: bool = False

    def display_name(self) -> str:
        """Return formatted representation of the target."""
        if self.port is not None:
            proto = f"/{self.protocol}" if self.protocol != "tcp" else ""
            return f"{self.port}{proto}"
        return self.host


class Observation(BaseModel):
    """Raw measurement record produced by a probe.

    Probes record purely what was seen without interpreting the data.
    """

    probe_name: str
    target: Target
    timestamp: float = Field(default_factory=time.time)
    success: bool = False
    raw: dict[str, Any] = Field(default_factory=dict)


class Verdict(BaseModel):
    """Normalized decision outcome generated by pure classifier functions."""

    target: Target
    kind: VerdictKind
    confidence: Confidence
    evidence: list[str] = Field(default_factory=list)


class Finding(BaseModel):
    """High-level policy finding synthesizing one or more verdicts."""

    title: str
    severity: Severity
    verdicts: list[Verdict] = Field(default_factory=list)
    summary: str


class ReportMetadata(BaseModel):
    """Audit run execution metadata and environment context."""

    tool_version: str = "0.1.0"
    network_label: str = "Guest-WiFi"
    network_fingerprint: str | None = None
    client_address: str = "192.168.1.100"
    run_time: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    )
    mode: str = "auto"
    runs_per_check: int = 5
    target: str | None = None
    include_identifiers: bool = False


class AuditReport(BaseModel):
    """Complete container for audit results, findings, and metadata."""

    schema_version: str = "1"
    metadata: ReportMetadata = Field(default_factory=ReportMetadata)
    port_results: list[Verdict] = Field(default_factory=list)
    dns_results: list[Verdict] = Field(default_factory=list)
    http_results: list[Verdict] = Field(default_factory=list)
    findings: list[Finding] = Field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """Convert the report to a JSON-compatible dictionary."""
        return self.model_dump(mode="json")

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> AuditReport:
        """Construct an AuditReport from a dictionary representation."""
        return cls.model_validate(data)


# Backwards compatibility alias
AuditSummary = AuditReport
